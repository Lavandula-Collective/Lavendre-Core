package com.lavandula.lavendrecore;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.fabricmc.api.ModInitializer;
import net.fabricmc.fabric.api.resource.ResourceManagerHelper;
import net.fabricmc.fabric.api.resource.ResourcePackActivationType;
import net.fabricmc.loader.api.FabricLoader;
import net.fabricmc.loader.api.ModContainer;
import net.minecraft.text.Text;
import net.minecraft.util.Identifier;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.Reader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

public class LavendreCore implements ModInitializer {
    public static final String MOD_ID = "lavendre_core";
    public static final Logger LOGGER = LoggerFactory.getLogger("Lavendre Core");

    // Folder names inside the jar's resourcepacks/ folder.
    // Resource pack and progression pack are hand-written. The data packs are generated by the build.
    public static final Identifier RESOURCE_PACK_ID = Identifier.of(MOD_ID, "lavendre_core_resources");
    public static final Identifier DATA_PACK_ID = Identifier.of(MOD_ID, "lavendre_core_data");
    public static final Identifier PROGRESSION_PACK_ID = Identifier.of(MOD_ID, "lavendre_core_progression");
    private static final String MODULE_PACK_PREFIX = "lavendre_core_module_";

    private record ModulePack(String id, String name, String requiredMod) {
    }

    @Override
    public void onInitialize() {
        LavendreConfig.load();
        LavendreConfig.Values config = LavendreConfig.session();
        boolean developerMode = config.developerMode();
        FabricLoader loader = FabricLoader.getInstance();

        loader.getModContainer(MOD_ID).ifPresent(container -> {
            // Resource pack: same in both modes.
            ResourceManagerHelper.registerBuiltinResourcePack(
                    RESOURCE_PACK_ID, container,
                    Text.literal("Lavendre Core Resources"),
                    ResourcePackActivationType.DEFAULT_ENABLED);

            // Copper progression: a tiny always-on pack, only registered when the toggle is on.
            if (config.copperProgression()) {
                ResourceManagerHelper.registerBuiltinResourcePack(
                        PROGRESSION_PACK_ID, container,
                        Text.literal("Lavendre Core: Progression"),
                        ResourcePackActivationType.ALWAYS_ENABLED);
            }

            if (developerMode) {
                registerModulePacks(loader, container);
            } else {
                ResourceManagerHelper.registerBuiltinResourcePack(
                        DATA_PACK_ID, container,
                        Text.literal("Lavendre Core Data"),
                        ResourcePackActivationType.DEFAULT_ENABLED);
            }

            String version = container.getMetadata().getVersion().getFriendlyString();
            LOGGER.info("Lavendre Core v{} loaded. Developer Mode: {}", version, developerMode ? "ON" : "OFF");
        });

        LOGGER.info("Features: copper progression {}, gold tools instant break {}, gold armor speed {}.",
                config.copperProgression() ? "ON" : "OFF",
                config.goldToolsInstantBreak() ? "ON" : "OFF",
                config.goldArmorSpeed() ? "ON" : "OFF");

        if (config.goldToolsInstantBreak()) {
            try {
                GoldTools.register();
            } catch (Throwable t) {
                LOGGER.error("GoldTools failed to register", t);
            }
        }
        if (config.goldArmorSpeed()) {
            try {
                GoldArmorSpeed.register();
            } catch (Throwable t) {
                LOGGER.error("GoldArmorSpeed failed to register", t);
            }
        }
    }

    /** Developer Mode: one pack per module, not enabled by default. */
    private static void registerModulePacks(FabricLoader loader, ModContainer container) {
        List<ModulePack> modules = readModuleIndex(container);
        if (modules.isEmpty()) {
            LOGGER.warn("Developer Mode is on, but no modules were found. Check src/modules in the project.");
            return;
        }

        for (ModulePack module : modules) {
            if (!module.requiredMod().isEmpty() && !loader.isModLoaded(module.requiredMod())) {
                LOGGER.info("Skipping module '{}' (mod '{}' is not loaded)", module.id(), module.requiredMod());
                continue;
            }

            ResourceManagerHelper.registerBuiltinResourcePack(
                    Identifier.of(MOD_ID, MODULE_PACK_PREFIX + module.id()), container,
                    Text.literal("Lavendre Core: " + module.name()),
                    ResourcePackActivationType.NORMAL);
        }
        LOGGER.info("Registered {} module pack(s), all disabled by default.", modules.size());
    }

    private static List<ModulePack> readModuleIndex(ModContainer container) {
        List<ModulePack> result = new ArrayList<>();
        Optional<Path> index = container.findPath("lavendre_modules.json");
        if (index.isEmpty()) {
            return result;
        }

        try (Reader reader = Files.newBufferedReader(index.get())) {
            JsonArray array = JsonParser.parseReader(reader).getAsJsonArray();
            for (JsonElement element : array) {
                JsonObject o = element.getAsJsonObject();
                String requiredMod = o.has("mod") ? o.get("mod").getAsString() : "";
                result.add(new ModulePack(o.get("id").getAsString(), o.get("name").getAsString(), requiredMod));
            }
        } catch (Exception e) {
            LOGGER.error("Could not read lavendre_modules.json", e);
        }
        return result;
    }
}